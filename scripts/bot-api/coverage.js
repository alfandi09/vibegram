// scripts/bot-api/coverage.js
// Compares a parsed Bot API snapshot with the hand-written declarations in src/types.ts.

'use strict';

const path = require('path');

/**
 * Reads exported interfaces/type aliases from a TypeScript file and returns
 * { [typeName]: { fields: { [field]: { optional } } | null } } (null = not an object type).
 */
function readDeclaredTypes(typesFile) {
    const ts = require('typescript');
    const program = ts.createProgram([typesFile], {
        strict: true,
        noEmit: true,
        skipLibCheck: true,
        types: ['node'],
    });
    const checker = program.getTypeChecker();
    const source = program.getSourceFile(typesFile);
    const moduleSymbol = checker.getSymbolAtLocation(source);
    const declared = {};
    for (const symbol of checker.getExportsOfModule(moduleSymbol)) {
        const decl = symbol.declarations && symbol.declarations[0];
        if (!decl || !(ts.isInterfaceDeclaration(decl) || ts.isTypeAliasDeclaration(decl))) continue;
        const type = checker.getDeclaredTypeOfSymbol(symbol);
        const fields = {};
        for (const prop of checker.getPropertiesOfType(type)) {
            fields[prop.getName()] = { optional: (prop.flags & ts.SymbolFlags.Optional) !== 0 };
        }
        declared[symbol.getName()] = { fields };
    }
    return declared;
}

function buildCoverage(spec, declared) {
    const missingTypes = [];
    const missingFields = [];
    const optionalityMismatches = [];
    let objectTypes = 0;
    let coveredTypes = 0;
    let totalFields = 0;
    let coveredFields = 0;

    for (const type of Object.values(spec.types)) {
        if (type.name === 'InputFile') continue;
        if (type.kind === 'object') objectTypes++;
        const local = declared[type.name];
        if (!local) {
            missingTypes.push(type.name);
            totalFields += type.fields.length;
            continue;
        }
        if (type.kind === 'object') coveredTypes++;
        for (const field of type.fields) {
            totalFields++;
            const localField = local.fields[field.name];
            if (!localField) {
                missingFields.push(`${type.name}.${field.name}`);
                continue;
            }
            coveredFields++;
            if (localField.optional === field.required) {
                optionalityMismatches.push(
                    `${type.name}.${field.name} (spec: ${field.required ? 'required' : 'optional'}, local: ${localField.optional ? 'optional' : 'required'})`
                );
            }
        }
    }

    return {
        version: spec.version,
        summary: {
            specTypes: Object.keys(spec.types).length,
            specMethods: Object.keys(spec.methods).length,
            objectTypes,
            coveredTypes,
            totalFields,
            coveredFields,
        },
        missingTypes: missingTypes.sort(),
        missingFields: missingFields.sort(),
        optionalityMismatches: optionalityMismatches.sort(),
    };
}

function renderCoverageMarkdown(report) {
    const s = report.summary;
    const list = items => (items.length ? items.map(i => `- \`${i}\``).join('\n') : '_None._');
    return [
        '# Bot API coverage report',
        '',
        '<!-- AUTO-GENERATED by scripts/generate-bot-api.js — do not edit by hand. -->',
        '',
        `Spec: Bot API ${report.version} — ${s.specTypes} types, ${s.specMethods} methods.`,
        `Compared against hand-written \`src/types.ts\`.`,
        '',
        `| Metric | Value |`,
        `| --- | --- |`,
        `| Object types declared | ${s.coveredTypes} / ${s.objectTypes} |`,
        `| Fields declared | ${s.coveredFields} / ${s.totalFields} |`,
        `| Missing types | ${report.missingTypes.length} |`,
        `| Missing fields (on declared types) | ${report.missingFields.length} |`,
        `| Optionality mismatches | ${report.optionalityMismatches.length} |`,
        '',
        '## Missing types',
        '',
        list(report.missingTypes),
        '',
        '## Missing fields',
        '',
        list(report.missingFields),
        '',
        '## Optionality mismatches',
        '',
        list(report.optionalityMismatches),
        '',
    ].join('\n');
}

module.exports = {
    readDeclaredTypes,
    buildCoverage,
    renderCoverageMarkdown,
    defaultTypesFile: path.join(__dirname, '..', '..', 'src', 'types.ts'),
};
