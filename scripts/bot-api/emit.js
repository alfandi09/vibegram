// scripts/bot-api/emit.js
// Turns a parsed Bot API snapshot into TypeScript source (types only).

'use strict';

const PRIMITIVES = {
    Integer: 'number',
    Int: 'number',
    Float: 'number',
    'Float number': 'number',
    String: 'string',
    Boolean: 'boolean',
    True: 'true',
    False: 'false',
};

function renderType(expr, knownTypes) {
    if (!expr) return 'unknown';
    if (expr.kind === 'array') {
        const inner = renderType(expr.of, knownTypes);
        return /[ |]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
    }
    if (expr.kind === 'union') {
        return [...new Set(expr.of.map(e => renderType(e, knownTypes)))].join(' | ');
    }
    if (PRIMITIVES[expr.name]) return PRIMITIVES[expr.name];
    if (expr.name === 'InputFile' || knownTypes.has(expr.name)) return expr.name;
    return 'unknown';
}

function comment(text, indent) {
    if (!text) return '';
    const safe = text.replace(/\*\//g, '*\\/');
    const lines = safe.split('\n');
    if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
    return `${indent}/**\n${lines.map(l => `${indent} * ${l}`).join('\n')}\n${indent} */\n`;
}

function propertyKey(name) {
    return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** Detects string enums such as 'always “photo”' or 'can be either “private”, “group” or “channel”'. */
function stringLiterals(description) {
    const single = description.match(/(?:always|must be) “([^”]+)”/);
    if (single) return [single[1]];
    const multi = description.match(/(?:can be either|can be one of|one of|either)((?:\s*,?\s*(?:or\s+)?“[^”]+”)+)/);
    if (!multi) return null;
    const values = [...multi[1].matchAll(/“([^”]+)”/g)].map(m => m[1]);
    return values.length > 1 ? values : null;
}

function renderField(field, knownTypes) {
    const literals = field.type === 'String' ? stringLiterals(field.description) : null;
    const type = literals
        ? literals.map(value => JSON.stringify(value)).join(' | ')
        : renderType(field.typeExpr, knownTypes);
    const optional = field.required ? '' : '?';
    return `${comment(field.description, '    ')}    ${propertyKey(field.name)}${optional}: ${type};\n`;
}

function header(spec) {
    return (
        '// AUTO-GENERATED by scripts/generate-bot-api.js — do not edit by hand.\n' +
        `// Source: https://core.telegram.org/bots/api (Bot API ${spec.version}, ${spec.date})\n\n`
    );
}

/** Emits src/bot-api-types.ts: every spec object/union type as a standalone declaration. */
function emitTypes(spec) {
    const knownTypes = new Set(Object.keys(spec.types));
    let out = header(spec);
    out += "import type { InputFile as VibegramInputFile } from './types';\n\n";
    out += '/** A file to upload: file_id/URL string, Buffer, stream or InputFileUpload. */\n';
    out += 'export type InputFile = VibegramInputFile;\n';

    for (const type of Object.values(spec.types)) {
        if (type.name === 'InputFile') continue;
        out += '\n' + comment(type.description, '');
        if (type.kind === 'union' && type.oneOf && type.oneOf.length > 0) {
            const members = type.oneOf.map(name => (knownTypes.has(name) ? name : 'unknown'));
            out += `export type ${type.name} = ${members.join(' | ')};\n`;
        } else if (type.fields.length === 0) {
            out += `export type ${type.name} = Record<string, never>;\n`;
        } else {
            out += `export interface ${type.name} {\n`;
            for (const field of type.fields) out += renderField(field, knownTypes);
            out += '}\n';
        }
    }
    return out;
}

/** Emits src/api-methods.ts: the ApiMethods map plus helper aliases. */
function emitMethods(spec) {
    const knownTypes = new Set(Object.keys(spec.types));
    const qualify = text =>
        text.replace(/\b([A-Z][A-Za-z0-9]*)\b/g, name =>
            knownTypes.has(name) || name === 'InputFile' ? `BotApi.${name}` : name
        );
    let out = header(spec);
    out += "import type * as BotApi from './bot-api-types';\n\n";
    out += "export type * as BotApi from './bot-api-types';\n\n";
    out += `/** Bot API version this map was generated from. */\n`;
    out += `export type BotApiVersion = ${JSON.stringify(spec.version)};\n\n`;
    out += '/**\n * Every Telegram Bot API method with its parameters and result type.\n */\n';
    out += 'export interface ApiMethods {\n';
    for (const method of Object.values(spec.methods)) {
        out += comment(method.description, '    ');
        out += `    ${method.name}: {\n`;
        if (method.params.length === 0) {
            out += '        params: Record<string, never>;\n';
        } else {
            out += '        params: {\n';
            for (const param of method.params) {
                out += comment(param.description, '            ');
                const type = qualify(renderType(param.typeExpr, knownTypes));
                out += `            ${propertyKey(param.name)}${param.required ? '' : '?'}: ${type};\n`;
            }
            out += '        };\n';
        }
        out += `        result: ${qualify(renderType(method.returns, knownTypes))};\n`;
        out += '    };\n';
    }
    out += '}\n\n';
    out += '/** Name of a known Bot API method. */\n';
    out += 'export type ApiMethodName = keyof ApiMethods;\n\n';
    out += '/** Parameters object for a known Bot API method. */\n';
    out += "export type ApiParams<M extends ApiMethodName> = ApiMethods[M]['params'];\n\n";
    out += '/** Result type for a known Bot API method. */\n';
    out += "export type ApiResult<M extends ApiMethodName> = ApiMethods[M]['result'];\n";
    return out;
}

module.exports = { emitTypes, emitMethods, renderType };
